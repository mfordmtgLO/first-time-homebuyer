import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

describe("single-property Cost of Waiting section", () => {
  it("renders the calculator in a visible standalone anchored section", () => {
    const page = readFileSync("client/src/pages/PropertyLandingPage.tsx", "utf8");
    const calculator = readFileSync("client/src/components/landing/CostOfWaiting.tsx", "utf8");
    const buydown = readFileSync("client/src/components/landing/Buydown.tsx", "utf8");
    expect(page).toContain('id="cost-of-waiting"');
    expect(page).toContain('background: "oklch(0.27 0.05 162)"');
    expect(page).toContain("What could waiting cost you while this opportunity changes?");
    expect(page).toContain("monthlyPropertyTaxes={snapshot.propertyTaxes === null ? undefined : snapshot.propertyTaxes / 12}");
    expect(page).toContain("monthlyHoaDues={snapshot.hoaDues ?? undefined}");
    expect(page).toContain("monthlyHomeownerInsurance={snapshot.homeownerInsurance ?? undefined}");
    expect(page).toContain("monthlyMortgageInsurance={snapshot.mortgageInsurance ?? undefined}");
    expect(page).toContain("Saved annual property taxes are divided by 12");
    expect(page).toContain("Saved HOA dues are treated as a monthly planning cost");
    expect(page).toContain("BuyerCalculationActions");
    expect(page).toContain("Your local homebuying team");
    expect(page).toContain("Email PDF summary");
    expect(page).toContain('eventType: "email_pdf_summary"');
    expect(page).toContain("CalculatorEligibilityBadges");
    expect(page).toContain("OHCS Flex Lending screen");
    expect(page).toContain("USDA RD screen");
    expect(page).toContain("outside USDA’s ineligible urban overlays");
    expect(page).toContain("PropertySectionNavigator");
    expect(page).toContain('new Event("open-mortgage-chat")');
    expect(page).toContain("window.addEventListener(\"scroll\", updateActiveSection");
    expect(calculator).toContain("prefilledPurchasePrice");
    expect(calculator).toContain("revealImmediately = false");
    expect(calculator).toContain('revealImmediately ? "opacity-100 translate-y-0" : "reveal"');
    expect(calculator).toContain("For {propertyAddress}");
    expect(calculator).toContain("Five-year buy-now vs. wait lens");
    expect(calculator).toContain("LineChart");
    expect(calculator).toContain("Share this scenario");
    expect(calculator).toContain("Cost of Waiting scenario");
    expect(calculator).toContain("FiveYearComparisonTooltip");
    expect(calculator).toContain("Five-year impact:");
    expect(calculator).toContain("Saved all-in monthly planning context");
    expect(calculator).toContain("monthlyPropertyTaxes?: number");
    expect(calculator).toContain("monthlyHoaDues?: number");
    expect(calculator).toContain("monthlyHomeownerInsurance?: number");
    expect(calculator).toContain("monthlyMortgageInsurance?: number");
    expect(buydown).toContain("propertyAddress?: string");
    expect(buydown).toContain("2-1 Buydown scenario for");
    expect(buydown).toContain("Share this scenario");
    expect(buydown).toContain("#buydown");
    expect(buydown).toContain("Potential monthly payment savings");
    expect(buydown).toContain("seller contributions toward the 2-1 buydown subsidy");
    expect(buydown).toContain("not a payment quote, APR quote");
    expect(buydown).not.toContain("Monthly principal & interest by year");
    expect(buydown).not.toContain("Estimated note-rate P&I");
    expect(page).not.toContain("Year 1 payment / savings");
  });
});
